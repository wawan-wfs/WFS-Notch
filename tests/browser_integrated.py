"""Full browser-preview app with real local persistence and explicit fixture-only native state."""
from pathlib import Path
import base64
import re
from shutil import which
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
UI = ROOT / 'src'
html = (UI / 'index.html').read_text(encoding='utf-8')
styles = re.findall(r'<link rel="stylesheet" href="([^"]+)">', html)
scripts = re.findall(r'<script src="([^"]+)" defer></script>', html)
html = re.sub(r'<script src="[^"]+" defer></script>', '', html)
html = re.sub(r'<link rel="stylesheet" href="[^"]+">', '', html)
logo = base64.b64encode((UI / 'assets/wfs-notch-mark.svg').read_bytes()).decode()
html = html.replace('src="assets/wfs-notch-mark.svg"', 'src="data:image/svg+xml;base64,' + logo + '"')
with sync_playwright() as pw:
    exe = which('chromium') or which('chromium-browser') or which('google-chrome')
    browser = pw.chromium.launch(**({'executable_path': exe} if exe else {}), headless=True, args=['--no-sandbox', '--disable-dev-shm-usage'])
    checks = 0
    def check(c, label):
        global checks
        assert c, label
        checks += 1
    for width, height, dpr in [(760,470,1),(560,420,1.5)]:
        page = browser.new_page(viewport={'width':width,'height':height}, device_scale_factor=dpr, bypass_csp=True, reduced_motion='reduce')
        errors = []
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.on('dialog', lambda d: d.accept())
        page.set_content(html)
        page.evaluate("""() => {const cache={};Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>cache[k]??null,setItem:(k,v)=>{cache[k]=String(v);},removeItem:k=>{delete cache[k];}}});}""")
        for name in styles:
            page.add_style_tag(content=(UI/name).read_text(encoding='utf-8'))
        page.add_style_tag(content='body.preview{padding-top:0!important}body.preview .notch{width:min(760px,100vw)!important;height:min(470px,100vh)!important}')
        for name in scripts:
            page.add_script_tag(content=(UI/name).read_text(encoding='utf-8'))
        page.locator('#expanded').wait_for(state='visible')
        page.wait_for_function("() => appDataLoadStatus==='ready'")
        page.evaluate("""async()=>{await mutation('add_todo',{title:'Integrated task',priority:'normal'});await mutation('add_habit',{title:'Read'});await mutation('add_quick_link',{label:'Old site',url:'https://example.com'});await switchTab('todos');}""")
        page.locator('#wfs52-task-form').evaluate("(e)=>e.closest('details').open=true")
        page.locator('#wfs52-task-list input').first.check()
        page.locator('#wfs52-task-priority').select_option('high')
        page.locator('#wfs52-task-apply').click()
        page.wait_for_function("()=>data.todos.some(t=>t.title==='Integrated task'&&t.priority==='high')")
        check(page.evaluate("()=>data.todos.find(t=>t.title==='Integrated task').change_token!=null"),'token updated')
        check(page.evaluate("()=>data.todos.find(t=>t.title==='Integrated task').due_at_ms==null"),'deadline preserved')
        page.locator('#wfs52-task-list input').first.check()
        page.locator('#wfs53-deadline').fill('2027-01-05T12:00')
        page.locator('#wfs53-deadline-set').click()
        page.wait_for_function("()=>data.todos.find(t=>t.title==='Integrated task').due_at_ms!=null")
        check(page.evaluate("()=>data.todos.find(t=>t.title==='Integrated task').priority==='high'"),'deadline keeps priority')
        page.evaluate("()=>switchTab('dock')")
        page.locator('#wfs52-shelf-json').evaluate("(e)=>e.closest('details').open=true")
        page.locator('#wfs52-shelf-json').fill('{"format":"wfs-notch-shelf-metadata","version":1,"entries":[{"name":"sample.pdf","size":123,"modified":1}]}')
        page.locator('#wfs52-shelf-preview').click()
        expect(page.locator('#wfs52-shelf-status')).to_contain_text('1 new')
        page.locator('#wfs52-shelf-apply').click()
        expect(page.locator('#shelf-list')).to_contain_text('sample.pdf')
        check(page.evaluate("()=>shelfEntries.length===1"),'one metadata entry')
        page.locator('#shelf-input').set_input_files([
            {'name':'sample.txt','mimeType':'text/plain','buffer':b'<script>literal</script>'},
            {'name':'other.txt','mimeType':'text/plain','buffer':b'Other selected file'},
        ])
        page.locator('#wfs52-file-select').evaluate("(e)=>e.closest('details').open=true")
        page.locator('#wfs52-file-select').select_option(value=page.evaluate(
            "()=>[...wfs52ShelfHandles.keys()].find(k=>JSON.parse(k)[0]==='sample.txt')"))
        expect(page.locator('#wfs54-shelf-release')).to_be_enabled()
        page.locator('#wfs52-file-open').click()
        expect(page.locator('#wfs52-file-content pre')).to_have_text('<script>literal</script>')
        check(page.locator('#wfs52-file-content script').count()==0,'text never interpreted')
        page.evaluate("""()=>{Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.fixtureClipboard=text;}}});}""")
        page.locator('#wfs54-shelf-copy').click()
        page.wait_for_function("()=>window.fixtureClipboard==='<script>literal</script>'")
        check(page.evaluate("()=>window.fixtureClipboard==='<script>literal</script>'"),'explicit clipboard fixture receives literal preview')
        page.locator('#wfs55-bundle-review').evaluate("(e)=>e.closest('details').open=true")
        page.locator('#wfs55-bundle-review').click()
        expect(page.locator('#wfs55-bundle-status')).to_contain_text('2 text files reviewed')
        expect(page.locator('#wfs55-bundle-text')).to_contain_text('<script>literal</script>')
        expect(page.locator('#wfs55-bundle-text')).to_contain_text('Other selected file')
        check(page.locator('#wfs55-bundle-text script').count()==0,'bundle literal not executable')
        page.locator('#wfs55-bundle-copy').click()
        page.wait_for_function("()=>window.fixtureClipboard.includes('Other selected file')")
        check(page.evaluate("()=>window.fixtureClipboard.includes('sample.txt')&&window.fixtureClipboard.includes('other.txt')"),'explicit bundle copy fixture')
        page.locator('#wfs56-bundle-choices label').filter(has_text='other.txt').locator('input').uncheck()
        expect(page.locator('#wfs55-bundle-copy')).to_be_disabled()
        page.locator('#wfs55-bundle-review').click()
        expect(page.locator('#wfs55-bundle-status')).to_contain_text('1 text files reviewed')
        expect(page.locator('#wfs55-bundle-text')).not_to_contain_text('Other selected file')
        page.locator('#wfs57-bundle-title').fill('Reviewed bundle test')
        expect(page.locator('#wfs57-bundle-note')).to_be_enabled()
        page.locator('#wfs57-bundle-note').click()
        page.wait_for_function("()=>data.notes.some(n=>n.title==='Reviewed bundle test'&&n.body.includes('<script>literal</script>')&&n.tags.includes('bundle'))")
        check(page.evaluate("()=>data.notes.filter(n=>n.title==='Reviewed bundle test').length===1"),'explicit reviewed bundle note created once')
        expect(page.locator('#wfs57-bundle-note')).to_be_disabled()
        page.locator('#wfs53-shelf-note').click()
        page.wait_for_function("()=>data.notes.some(n=>n.title==='sample.txt'&&n.body==='<script>literal</script>')")
        check(page.evaluate("()=>data.notes.some(n=>n.tags.includes('shelf'))"),'explicit local note created')
        page.locator('#wfs54-shelf-release').click()
        check(page.locator('#wfs52-file-content').inner_text()=='','individual release clears preview')
        expect(page.locator('#wfs54-shelf-copy')).to_be_disabled()
        expect(page.locator('#wfs55-bundle-copy')).to_be_disabled()
        check(page.locator('#wfs55-bundle-text').text_content()=='','release invalidates reviewed bundle')
        check(page.evaluate("()=>wfs52ShelfHandles.size===1&&[...wfs52ShelfHandles.keys()].some(k=>JSON.parse(k)[0]==='other.txt')"),'individual release retains other selected handle')
        page.locator('#wfs52-file-forget').click()
        check(page.locator('#wfs52-file-content').inner_text()=='','release content')
        check(page.evaluate("()=>shelfEntries.length===3&&wfs52ShelfHandles.size===0"),'metadata preserved after releasing files')
        page.locator('#wfs52-link-form').evaluate("(e)=>e.closest('details').open=true")
        page.locator('#wfs52-link-select').select_option(label='Old site')
        page.locator('#wfs52-link-load').click()
        page.locator('#wfs52-link-title').fill('New site')
        page.locator('#wfs52-link-apply').click()
        page.wait_for_function("()=>data.quick_links.some(x=>x.label==='New site')")
        check(page.evaluate("()=>data.quick_links[0].url==='https://example.com/'"),'URL preserved')
        page.evaluate("()=>switchTab('habits')")
        page.locator('#wfs52-habit-form').evaluate("(e)=>e.closest('details').open=true")
        page.locator('#wfs52-habit-select').select_option(label='Read')
        page.locator('#wfs52-habit-load').click()
        page.locator('#wfs52-habit-title').fill('Read daily')
        page.locator('#wfs52-habit-apply').click()
        page.wait_for_function("()=>data.habits.some(x=>x.title==='Read daily')")
        check(page.evaluate("()=>data.habits.length===1"),'rename retains identity')
        page.evaluate("()=>switchTab('health')")
        page.locator('#phase51-health-form').evaluate("(e)=>e.closest('details').open=true")
        page.locator('#phase51-water').fill('10')
        page.locator('#phase51-health-form button[type=submit]').click()
        page.wait_for_function("()=>data.settings.health_targets.water===10")
        check(page.evaluate("()=>JSON.parse(localStorage.getItem('wfs-notch-browser-preview-v2')).settings.health_targets.water===10"),'health target persisted')
        page.evaluate("()=>switchTab('weather')")
        page.evaluate("()=>{localStorage.setItem('wfs-notch-weather-city','Fixture');document.querySelector('#weather-city').value='Fixture';}")
        page.locator('#wfs52-weather-forget').click()
        check(page.evaluate("()=>localStorage.getItem('wfs-notch-weather-city')===null"),'city forgotten')
        page.evaluate("()=>switchTab('system')")
        expect(page.locator('#wfs52-volume-apply')).to_be_disabled()
        check(page.evaluate("()=>wfs52Output===null"),'no synthetic Windows volume')
        expect(page.locator('#wfs55-audio-read')).to_be_disabled()
        check(page.locator('#wfs55-audio-rows').count()==1 and page.locator('#wfs55-audio-rows').text_content()=='','no synthetic audio role matrix')
        page.evaluate("()=>switchTab('media')")
        expect(page.locator('#wfs52-seek-apply')).to_be_disabled()
        check(page.evaluate("()=>!nativeInvoke"),'no native simulation')
        check(page.locator('.wfs53-context').count()==16,'all module context surfaces')
        check(page.locator('.wfs56-landmarks').count()==16,'all workspace landmark surfaces')
        check(page.locator('.wfs56-landmarks button').count()==48,'all independent section actions')
        page.evaluate("()=>switchTab('notes')")
        page.locator('#panel-notes .wfs56-landmarks').get_by_role('button',name='Search',exact=True).click()
        check(page.locator('#note-search').evaluate('(e)=>document.activeElement===e'),'workspace jump focuses existing control')
        page.evaluate("()=>switchTab('media')")
        page.evaluate("""async()=>{
            await invoke('create_backup');
            const task=data.todos.find(t=>t.title==='Integrated task');
            await mutation('update_todo',{id:task.id,title:'Edited after snapshot',priority:task.priority,dueAtMs:task.due_at_ms,recurrence:null});
            await mutation('add_todo',{title:'After snapshot'});
            await switchTab('settings');await refreshBackups();
        }""")
        page.locator('#backup-list button[aria-label^="Review backup"]').first.click()
        expect(page.locator('#wfs53-restore-status')).to_contain_text('Review ready')
        check('1 removed IDs' in page.locator('#wfs53-restore-rows').inner_text(),'removal visible in review')
        check('1 retained records changed' in page.locator('#wfs53-restore-rows').inner_text(),'retained record edit visible without title')
        expect(page.locator('#wfs55-restore-impact')).to_contain_text('1 removed')
        expect(page.locator('#wfs55-restore-impact')).to_contain_text('1 changed')
        expect(page.locator('#wfs56-restore-risk')).to_contain_text('tasks: 1 removed, 1 changed')
        expect(page.locator('#wfs55-os-consent')).to_be_disabled()
        expect(page.locator('#wfs55-os-read')).to_be_disabled()
        check(page.locator('#wfs55-os-rows').text_content()=='','no synthetic OS notifications')
        check('Edited after snapshot' not in page.locator('#wfs53-restore-rows').inner_text(),'review does not expose task title')
        page.evaluate("()=>mutation('add_todo',{title:'Stale review change'})")
        page.locator('#wfs53-restore-apply').click()
        expect(page.locator('#wfs53-restore-status')).to_contain_text('changed')
        check(page.evaluate("()=>data.todos.some(t=>t.title==='Stale review change')"),'stale review did not restore')
        page.locator('#backup-list button[aria-label^="Review backup"]').first.click()
        expect(page.locator('#wfs53-restore-status')).to_contain_text('Review ready')
        page.locator('#wfs53-restore-apply').click()
        expect(page.locator('#wfs53-restore-status')).to_contain_text('Protective snapshot saved')
        check(page.evaluate("()=>!data.todos.some(t=>t.title==='After snapshot')"),'reviewed restore applied')
        check(page.evaluate("()=>data.todos.some(t=>t.title==='Integrated task')&&!data.todos.some(t=>t.title==='Edited after snapshot')"),'retained edit restored')
        expect(page.locator('#wfs55-restore-impact')).to_have_text('No impact reviewed.')
        check(page.evaluate("()=>JSON.parse(localStorage.getItem(previewBackupsKey)).length>=2"),'protective backup exists')
        check(not errors,'no JavaScript errors '+str(errors))
        out=ROOT/'test-results';out.mkdir(exist_ok=True)
        page.screenshot(path=str(out/f'browser-integrated-{width}-{dpr}.png'))
        page.close()
    browser.close()
    print(f'PASS: {checks} integrated full browser assertions (native seek not simulated)')
